create table employee (
    id bigint generated by default as identity,
    employee_code varchar(50) not null,
    full_name varchar(200) not null,
    department varchar(100) not null,
    work_country char(2) not null,
    active boolean not null,
    version bigint not null default 0,
    constraint pk_employee primary key (id),
    constraint uk_employee_code unique (employee_code),
    constraint ck_employee_code_not_blank check (btrim(employee_code) <> ''),
    constraint ck_employee_full_name_not_blank check (btrim(full_name) <> ''),
    constraint ck_employee_department_not_blank check (btrim(department) <> ''),
    constraint ck_employee_work_country_format check (work_country ~ '^[A-Z]{2}$'),
    constraint ck_employee_version_non_negative check (version >= 0)
);

create table salary_revision (
    id bigint generated by default as identity,
    employee_id bigint not null,
    annual_base_amount numeric(19, 4) not null,
    currency_code char(3) not null,
    effective_date date not null,
    reason varchar(500) not null,
    recorded_at timestamp with time zone not null default current_timestamp,
    constraint pk_salary_revision primary key (id),
    constraint fk_salary_revision_employee foreign key (employee_id)
        references employee (id) on delete restrict,
    constraint uk_salary_revision_employee_effective_date
        unique (employee_id, effective_date),
    constraint ck_salary_revision_amount_positive check (annual_base_amount > 0),
    constraint ck_salary_revision_currency_format check (currency_code ~ '^[A-Z]{3}$'),
    constraint ck_salary_revision_reason_not_blank check (btrim(reason) <> '')
);

create index ix_employee_work_country on employee (work_country);
create index ix_employee_department on employee (department);
